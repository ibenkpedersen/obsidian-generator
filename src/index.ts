import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { confirm, intro, multiselect, note, outro, text } from "@clack/prompts";

export type FeatureName = "editor-heading-extension";

export const FEATURE_OPTIONS: Array<{ value: FeatureName; label: string; hint: string }> = [
  {
    value: "editor-heading-extension",
    label: "Editor-udvidelse til overskrifter",
    hint: "CodeMirror 6-udvidelse, der markerer overskrifter i editoren",
  },
];

type PluginOptions = {
  name: string;
  id: string;
  description: string;
  author: string;
  projectDir: string;
  vaultDir: string;
  features?: FeatureName[];
};

export function slugify(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "my-plugin";
}

function pascalCase(value: string): string {
  return value
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("") || "MyPlugin";
}

function isCancelled(value: string | boolean | symbol | string[] | undefined): value is symbol {
  return typeof value === "symbol";
}

function writeFile(targetPath: string, content: string): void {
  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  fs.writeFileSync(targetPath, content, "utf8");
}

function hasFeature(features: FeatureName[] | undefined, name: FeatureName): boolean {
  return (features ?? []).includes(name);
}

function buildManifest({ id, name, description, author }: Pick<PluginOptions, "id" | "name" | "description" | "author">): string {
  return JSON.stringify(
    {
      id,
      name,
      version: "0.1.0",
      minAppVersion: "1.5.3",
      description,
      author,
      isDesktopOnly: false,
    },
    null,
    2,
  );
}

function buildPackageJson({ id, name, description, author }: Pick<PluginOptions, "id" | "name" | "description" | "author">): string {
  return JSON.stringify(
    {
      name: id,
      version: "0.1.0",
      description,
      main: "main.js",
      author,
      scripts: {
        dev: "node esbuild.config.mjs --watch",
        build: "node esbuild.config.mjs",
      },
      devDependencies: {
        "@codemirror/state": "^6.7.6",
        "@codemirror/view": "^6.7.6",
        esbuild: "^0.24.0",
        obsidian: "^1.8.7",
      },
      private: true,
    },
    null,
    2,
  );
}

function buildTsconfig(): string {
  return JSON.stringify(
    {
      compilerOptions: {
        target: "ES2022",
        module: "ESNext",
        moduleResolution: "Bundler",
        lib: ["ES2022"],
        strict: true,
        allowSyntheticDefaultImports: true,
        esModuleInterop: true,
        skipLibCheck: true,
        noEmit: false,
      },
      include: ["src/**/*.ts"],
    },
    null,
    2,
  );
}

function buildMainTs(name: string, className: string, features: FeatureName[] = []): string {
  const imports: string[] = ['import { Plugin, Notice } from "obsidian";'];
  const body: string[] = [
    `  private readonly headingExtension = headingEditorExtension;`,
    "",
    "  async onload(): Promise<void> {",
    `    new Notice("${name} er aktiveret");`,
  ];

  if (hasFeature(features, "editor-heading-extension")) {
    imports.push('import { headingEditorExtension } from "./features/heading-editor";');
    body.push("    this.registerEditorExtension(this.headingExtension);");
  }

  body.push("  }");
  body.push("");
  body.push("  async onunload(): Promise<void> {");
  body.push(`    new Notice("${name} er deaktiveret");`);
  body.push("  }");
  body.push("}");

  return `
${imports.join("\n")}

export default class ${className} extends Plugin {
${body.join("\n")}
`;
}

function buildStylesCss(): string {
  return `/* Minimal plugin styles */\n`;
}

function buildEsbuildConfig(): string {
  return `import esbuild from "esbuild";

const isWatch = process.argv.includes("--watch");

const context = await esbuild.context({
  entryPoints: ["src/main.ts"],
  bundle: true,
  format: "cjs",
  platform: "node",
  target: "es2022",
  outfile: "main.js",
  external: ["obsidian", "@codemirror/view"],
  sourcemap: "inline",
  banner: {
    js: "// Generated by obsidian-plugin-generator",
  },
});

if (isWatch) {
  await context.watch();
  console.log("Watching for changes...");
} else {
  await context.rebuild();
  await context.dispose();
}
`;
}

function buildHeadingEditorExtension(): string {
  return `import { Decoration, EditorView } from "@codemirror/view";
import { RangeSetBuilder } from "@codemirror/state";

function headingLevel(line: string): number | null {
  const trimmed = line.trimStart();
  const match = trimmed.match(/^(#{1,6})\s+\S/);
  return match ? match[1].length : null;
}

export const headingEditorExtension = [
  EditorView.baseTheme({
    ".heading-demo-line": {
      borderLeft: "3px solid rgba(82, 156, 255, 0.9)",
      paddingLeft: "0.55rem",
      marginLeft: "0.35rem",
      borderRadius: "4px",
      background: "rgba(82, 156, 255, 0.08)",
      boxSizing: "border-box",
    },
    ".heading-demo-h1": { fontSize: "1.55em", fontWeight: "700", letterSpacing: "0.02em" },
    ".heading-demo-h2": { fontSize: "1.35em", fontWeight: "700", letterSpacing: "0.015em" },
    ".heading-demo-h3": { fontSize: "1.18em", fontWeight: "700" },
    ".heading-demo-h4": { fontSize: "1.08em", fontWeight: "700" },
    ".heading-demo-h5": { fontSize: "1em", fontWeight: "700" },
    ".heading-demo-h6": { fontSize: "0.95em", fontWeight: "700" },
  }),
  EditorView.decorations.of((view) => {
    const builder = new RangeSetBuilder<Decoration>();

    for (let lineNo = 1; lineNo <= view.state.doc.lines; lineNo++) {
      const line = view.state.doc.line(lineNo);
      const level = headingLevel(line.text);

      if (level === null) {
        continue;
      }

      const className = "heading-demo-line heading-demo-h" + level;
      builder.add(line.from, line.to, Decoration.line({ attributes: { class: className } }));
    }

    return builder.finish();
  }),
];
`;
}

function buildReadme(name: string): string {
  return `# ${name}

Et simpelt Obsidian-plugin.

## Kør lokalt

\`npm install\`
\`npm run dev\`

Dette bygger pluginet i watch-mode, så ændringer bliver kompileret automatisk.
`;
}

export function createPlugin(options: PluginOptions): void {
  const { projectDir, name, id, description, author, features = [] } = options;
  fs.mkdirSync(projectDir, { recursive: true });
  fs.mkdirSync(path.join(projectDir, "src"), { recursive: true });

  if (hasFeature(features, "editor-heading-extension")) {
    fs.mkdirSync(path.join(projectDir, "src", "features"), { recursive: true });
  }

  writeFile(path.join(projectDir, "manifest.json"), buildManifest({ id, name, description, author }));
  writeFile(path.join(projectDir, "package.json"), buildPackageJson({ id, name, description, author }));
  writeFile(path.join(projectDir, "tsconfig.json"), buildTsconfig());
  writeFile(path.join(projectDir, "README.md"), buildReadme(name));
  writeFile(path.join(projectDir, "styles.css"), buildStylesCss());
  writeFile(path.join(projectDir, "esbuild.config.mjs"), buildEsbuildConfig());
  writeFile(path.join(projectDir, "src/main.ts"), buildMainTs(name, pascalCase(id), features));

  if (hasFeature(features, "editor-heading-extension")) {
    writeFile(path.join(projectDir, "src", "features", "heading-editor.ts"), buildHeadingEditorExtension());
  }

  const gitignore = ["node_modules/", "main.js", "*.log"].join("\n");
  writeFile(path.join(projectDir, ".gitignore"), gitignore);
}

export function ensureSymlink(projectDir: string, vaultDir: string, pluginId: string): void {
  const targetDir = path.join(vaultDir, ".obsidian", "plugins", pluginId);
  fs.mkdirSync(path.dirname(targetDir), { recursive: true });

  if (fs.existsSync(targetDir) || fs.lstatSync(targetDir, { throwIfNoEntry: false }) !== undefined) {
    fs.rmSync(targetDir, { recursive: true, force: true });
  }

  fs.symlinkSync(projectDir, targetDir, "dir");
}

async function main(): Promise<void> {
  intro("Obsidian plugin generator");

  const nameResult = await text({
    message: "Plugin navn",
    placeholder: "Mit plugin",
    validate: (value) => (value.trim().length > 0 ? undefined : "Navn er påkrævet"),
  });

  if (isCancelled(nameResult)) {
    process.exit(0);
  }

  const name = String(nameResult).trim();
  const defaultId = slugify(name);

  const idResult = await text({
    message: "Plugin ID",
    placeholder: defaultId,
    defaultValue: defaultId,
    validate: (value) => (value.trim().length > 0 ? undefined : "Plugin ID er påkrævet"),
  });

  if (isCancelled(idResult)) {
    process.exit(0);
  }

  const id = slugify(String(idResult));

  const descriptionResult = await text({
    message: "Beskrivelse",
    placeholder: "Kort beskrivelse af pluginet",
    defaultValue: "",
  });

  if (isCancelled(descriptionResult)) {
    process.exit(0);
  }

  const description = String(descriptionResult).trim();

  const authorResult = await text({
    message: "Forfatter",
    placeholder: "Dit navn",
    defaultValue: "Anonymous",
  });

  if (isCancelled(authorResult)) {
    process.exit(0);
  }

  const author = String(authorResult).trim() || "Anonymous";

  const defaultProjectDir = path.join(process.cwd(), "plugins", id);
  const projectDirResult = await text({
    message: "Hvor skal pluginet oprettes?",
    placeholder: defaultProjectDir,
    defaultValue: defaultProjectDir,
  });

  if (isCancelled(projectDirResult)) {
    process.exit(0);
  }

  const projectDir = path.resolve(String(projectDirResult));

  const vaultDirResult = await text({
    message: "Sti til test-vaulten",
    placeholder: path.join(os.homedir(), "Obsidian", "TestVault"),
    defaultValue: path.join(os.homedir(), "Obsidian", "TestVault"),
  });

  if (isCancelled(vaultDirResult)) {
    process.exit(0);
  }

  const vaultDir = path.resolve(String(vaultDirResult));

  const featureResult = await multiselect({
    message: "Vælg feature-moduler",
    options: FEATURE_OPTIONS.map((option) => ({
      value: option.value,
      label: option.label,
      hint: option.hint,
    })),
    initialValues: [],
  });

  if (isCancelled(featureResult)) {
    process.exit(0);
  }

  const features = Array.isArray(featureResult) ? (featureResult as FeatureName[]) : [];

  const useSymlink = await confirm({
    message: "Opret symlink til test-vaulten?",
    initialValue: true,
  });

  if (isCancelled(useSymlink)) {
    process.exit(0);
  }

  createPlugin({
    name,
    id,
    description,
    author,
    projectDir,
    vaultDir,
    features,
  });

  if (useSymlink) {
    ensureSymlink(projectDir, vaultDir, id);
  }

  const nextSteps = [
    "1. cd \"${projectDir}\"",
    "2. npm install",
    "3. npm run dev   # udvikling i watch-mode",
    "4. npm run build  # bygges én gang til release/Obsidian",
    "",
    useSymlink ? `Symlink: ${path.join(vaultDir, ".obsidian", "plugins", id)}` : "Ingen symlink blev oprettet.",
  ].join("\n");

  note(nextSteps, "Næste skridt");

  outro(`Kom godt i gang med ${name}!`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
